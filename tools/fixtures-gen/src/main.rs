//! Usage:
//!   pdot-fixtures-gen header        > tests/fixtures/signer_vectors.h
//!   pdot-fixtures-gen verify < sigs.txt
//!   pdot-fixtures-gen golden <metadata.scale> > tests/fixtures/tx_golden.h
//!
//! `verify` reads lines "<scheme> <public hex> <message hex> <signature hex>"
//! produced by libpdot and checks each with sp-core.

use sp_core::{crypto::Pair as _, ecdsa, sr25519};
use std::io::BufRead;
use subxt_core::{
    client::{ClientState, RuntimeVersion},
    config::{DefaultExtrinsicParamsBuilder, PolkadotConfig},
    dynamic::Value,
    utils::{AccountId32, MultiSignature},
};

const URIS: &[&str] = &["//Alice", "//Bob", "//Bulletin"];

fn messages() -> Vec<Vec<u8>> {
    vec![
        vec![],
        b"hello bulletin".to_vec(),
        (0..32u8).collect(),
        (0..300u32).map(|i| (i * 7) as u8).collect(),
    ]
}

fn c_bytes(b: &[u8]) -> String {
    let body: Vec<String> = b.iter().map(|x| format!("0x{x:02x}")).collect();
    format!("{{ {} }}", body.join(", "))
}

fn header() {
    let msgs = messages();
    println!("/* Generated by tools/fixtures-gen with sp-core. Do not edit. */");
    println!("#include <stdint.h>\n#include <stddef.h>\n");

    println!("static const uint8_t vec_msg_0[1] = {{ 0 }};");
    for (i, m) in msgs.iter().enumerate().skip(1) {
        println!("static const uint8_t vec_msg_{i}[{}] = {};", m.len(), c_bytes(m));
    }
    println!("static const struct {{ const uint8_t *p; size_t len; }} vec_msgs[] = {{");
    for (i, m) in msgs.iter().enumerate() {
        println!("    {{ vec_msg_{i}, {} }},", m.len());
    }
    println!("}};\n#define VEC_NMSGS {}\n", msgs.len());

    println!("struct sr25519_vector {{\n    const char *uri;\n    uint8_t seed[32];\n    uint8_t public_key[32];\n    uint8_t sigs[{}][64];\n}};", msgs.len());
    println!("static const struct sr25519_vector sr25519_vectors[] = {{");
    for uri in URIS {
        let (pair, seed) = sr25519::Pair::from_string_with_seed(uri, None).unwrap();
        let seed = seed.unwrap();
        println!("  {{ \"{uri}\",\n    {},\n    {},\n    {{", c_bytes(&seed), c_bytes(&pair.public().0));
        for m in &msgs {
            println!("      {},", c_bytes(&pair.sign(m).0));
        }
        println!("    }} }},");
    }
    println!("}};\n");

    println!("struct ecdsa_vector {{\n    const char *uri;\n    uint8_t seed[32];\n    uint8_t public_key[33];\n    uint8_t sigs[{}][65];\n}};", msgs.len());
    println!("static const struct ecdsa_vector ecdsa_vectors[] = {{");
    for uri in URIS {
        let (pair, seed) = ecdsa::Pair::from_string_with_seed(uri, None).unwrap();
        let seed = seed.unwrap();
        println!("  {{ \"{uri}\",\n    {},\n    {},\n    {{", c_bytes(&seed), c_bytes(&pair.public().0));
        for m in &msgs {
            println!("      {},", c_bytes(&pair.sign(m).0));
        }
        println!("    }} }},");
    }
    println!("}};");
}

fn verify() -> bool {
    let mut ok = true;
    let mut n = 0;
    for line in std::io::stdin().lock().lines() {
        let line = line.unwrap();
        let f: Vec<&str> = line.split_whitespace().collect();
        if f.len() != 4 {
            continue;
        }
        let msg = if f[2] == "-" { vec![] } else { hex::decode(f[2]).unwrap() };
        let good = match f[0] {
            "sr25519" => {
                let pk = sr25519::Public::from_raw(hex::decode(f[1]).unwrap().try_into().unwrap());
                let sig = sr25519::Signature::from_raw(hex::decode(f[3]).unwrap().try_into().unwrap());
                sr25519::Pair::verify(&sig, &msg, &pk)
            }
            "ecdsa" => {
                let pk = ecdsa::Public::from_raw(hex::decode(f[1]).unwrap().try_into().unwrap());
                let sig = ecdsa::Signature::from_raw(hex::decode(f[3]).unwrap().try_into().unwrap());
                ecdsa::Pair::verify(&sig, &msg, &pk)
            }
            s => panic!("unknown scheme {s}"),
        };
        n += 1;
        if !good {
            eprintln!("FAIL: {line}");
            ok = false;
        }
    }
    println!("{n} signatures checked, {}", if ok { "all valid" } else { "FAILURES" });
    ok && n > 0
}

/// subxt-core signer backed by sp-core ECDSA, so signatures are deterministic.
struct EcdsaSigner(ecdsa::Pair);

impl subxt_core::tx::signer::Signer<PolkadotConfig> for EcdsaSigner {
    fn account_id(&self) -> AccountId32 {
        AccountId32(sp_crypto_hashing::blake2_256(&self.0.public().0))
    }
    fn sign(&self, payload: &[u8]) -> MultiSignature {
        MultiSignature::Ecdsa(self.0.sign(payload).0)
    }
}

/// Fixed inputs shared with tests/test_tx.c.
const G_GENESIS: [u8; 32] = [0x11; 32];
const G_CHECKPOINT_HASH: [u8; 32] = [0x22; 32];
const G_CHECKPOINT: u64 = 1234;
const G_SPEC: u32 = 1000026;
const G_TXVER: u32 = 1;
const G_NONCE: u64 = 7;

fn golden(path: &str) {
    let bytes = std::fs::read(path).unwrap();
    let metadata = subxt_core::metadata::decode_from(&bytes).unwrap();
    let state = ClientState::<PolkadotConfig> {
        genesis_hash: G_GENESIS.into(),
        runtime_version: RuntimeVersion { spec_version: G_SPEC, transaction_version: G_TXVER },
        metadata,
    };
    let (alice, _) = ecdsa::Pair::from_string_with_seed("//Alice", None).unwrap();
    let signer = EcdsaSigner(alice);
    let params = || {
        DefaultExtrinsicParamsBuilder::<PolkadotConfig>::new()
            .nonce(G_NONCE)
            .mortal_from_unchecked(64, G_CHECKPOINT, G_CHECKPOINT_HASH.into())
            .build()
    };

    let data: Vec<u8> = (0..300u32).map(|i| (i * 13) as u8).collect();
    let store = subxt_core::dynamic::tx("TransactionStorage", "store", vec![Value::from_bytes(&data)]);
    let renew = subxt_core::dynamic::tx(
        "DataRenewal",
        "force_renew",
        vec![Value::unnamed_variant("ContentHash", [Value::from_bytes([0x33u8; 32])])],
    );

    println!("/* Generated by tools/fixtures-gen golden with subxt-core from {}. */", path.rsplit('/').next().unwrap());
    let (alice_sr, _) = sr25519::Pair::from_string_with_seed("//Alice", None).unwrap();
    let auth = subxt_core::dynamic::storage(
        "TransactionStorage",
        "Authorizations",
        vec![Value::unnamed_variant("Account", [Value::from_bytes(alice_sr.public().0)])],
    );
    let key = subxt_core::storage::get_address_bytes(&auth, &state.metadata).unwrap();
    println!("static const char golden_auth_key_alice[] = \"{}\";", hex::encode(key));
    for (name, call) in [("store", &store), ("force_renew", &renew)] {
        let tx = subxt_core::tx::create_v4_signed(call, &state, params()).unwrap().sign(&signer);
        println!("static const char golden_{name}[] = \"{}\";", hex::encode(tx.into_encoded()));
    }
}

fn main() {
    match std::env::args().nth(1).as_deref() {
        Some("header") => header(),
        Some("verify") => std::process::exit(if verify() { 0 } else { 1 }),
        Some("golden") => golden(&std::env::args().nth(2).expect("metadata path")),
        _ => {
            eprintln!("usage: pdot-fixtures-gen header|verify|golden <metadata>");
            std::process::exit(2)
        }
    }
}
